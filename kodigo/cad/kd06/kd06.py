"""
Kodigo KD-06 "bracelet" - wrist remote case for Kodigo (parametric CadQuery).
Designer: Hoofie Puppet. License CC BY-NC-SA 4.0.

Watch-style case on a standard 20 mm watch strap (spring bars).
Coordinates (mm): X = across the wrist (+X = thumb side: USB-C and power switch),
Y = along the strap (lugs at +Y / -Y), Z = up from the wrist.

Inside (first guess, check against real parts):
  floor layer : LiPo 502030 (5 x 20 x 30) and TP4056 USB-C charger (about 26 x 17)
  upper layer : ESP32-C3 SuperMini on the LiPo, button board (3 x 6x6x5 THT) on the charger
Buttons: three printed plungers through the lid, shapes differ so you can tell them by feel
(plain / dimple / cross groove).
Logo chip: a recess in the top of the lid takes a separately printed two-colour chip
(Kodigo logo traced from kodigo-logo.png, redrawn bolder: glasses icon above the word,
strokes about 1 mm or more, three thick bars in the lens, so it prints cleanly with a 0.4 mm nozzle). Print the chip face up: base plate in colour A, change
filament at the plate/logo boundary (0.6 mm), logo in colour B. Glue the chip in (clear epoxy works), then fill the
recess level with clear 2-part resin: the chip sits 0.6 mm below the lid top, so the resin is 0.6 mm deep over the logo.
Screws: 4 x M2 x 10 (lid to base) into M2 heat-set inserts (3.2 mm outside diameter).
"""
import math, os, sys
import cadquery as cq

# ---- case ----
IN_X, IN_Y = 34.0, 50.0
WALL = 2.4
OUT_X, OUT_Y = IN_X + 2 * WALL, IN_Y + 2 * WALL
CORNER_R = 7.0
FLOOR = 2.4
BASE_H = 9.0              # split plane
CEIL_Z = 15.2             # inside ceiling of the lid
TOP_Z = CEIL_Z + 2.4      # overall height

# ---- parts (with ~0.3 mm clearance per side already added) ----
LIPO_X, LIPO_Y, LIPO_T = 20.6, 30.4, 5.5
LIPO_CY = -9.4
TP_X, TP_Y, TP_T = 26.4, 17.4, 4.2
TP_CY = 15.6
ESP_X, ESP_Y = 18.6, 23.1
ESP_CY = -11.0           # sits on the LiPo, clear of the lid lip at the -Y end

# ---- strap lugs (standard 20 mm) ----
STRAP_W = 20.0
HORN_T = 4.0
BAR_Y = 30.0              # spring bar axis
BAR_Z = 4.5
BAR_HOLE_D, BAR_HOLE_DEPTH = 1.9, 2.0

# ---- screws / posts ----
POST_D = 5.2
POST_XY = [(sx * 15.9, sy * 22.8) for sx in (-1, 1) for sy in (-1, 1)]   # four corners: even clamping
INSERT_D, INSERT_DEPTH = 3.2, 4.2
SCREW_HOLE_D, CBORE_D, CBORE_DEPTH = 2.4, 4.4, 1.6

# ---- buttons ----
BTN_X = (-10.0, 0.0, 10.0)
BTN_Y = TP_CY
HOLE_D = 6.4
STEM_D, FLANGE_D, FLANGE_T = 5.8, 8.4, 1.0
STEM_H = 3.6              # above the flange; tip ends 0.5 mm proud of the lid top

# ---- logo chip (flush insert in the lid top) ----
CHIP_W, CHIP_H = 32.0, 16.0       # chip size (bold stacked logo: 30.2 mm wide, 14.4 mm tall)
CHIP_BASE, CHIP_LOGO = 0.6, 0.4   # plate thickness, raised logo height -> 1.0 mm chip
CHIP_CLR = 0.2                    # clearance per side in the pocket (fine for PLA, PETG, TPU)
CHIP_CY = -6.0                    # Y position on the lid (logo runs along the case, clear of the buttons)
POCKET_DEPTH = 1.6                # recess depth: chip sits 0.6 mm below the lid top = room for the resin

SIG = "HP-KD06-26"
SIG_DEPTH = 0.4


def rr(w, h, r, z0, z1, cx=0.0, cy=0.0):
    return (cq.Workplane("XY", origin=(0, 0, z0)).center(cx, cy).rect(w, h)
            .extrude(z1 - z0).edges("|Z").fillet(r))


def box(x0, x1, y0, y1, z0, z1):
    return cq.Workplane("XY").box(x1 - x0, y1 - y0, z1 - z0, centered=False).translate((x0, y0, z0))


def cyl_z(x, y, z0, z1, d):
    return cq.Workplane("XY", origin=(x, y, z0)).circle(d / 2).extrude(z1 - z0)


def engrave_up(origin, txt, size):
    """Text cut into an upward-facing surface at origin (reads from above)."""
    o = (origin[0], origin[1], origin[2] - SIG_DEPTH)
    return cq.Workplane(cq.Plane(origin=o, xDir=(1, 0, 0), normal=(0, 0, 1))).text(
        txt, size, SIG_DEPTH + 0.01, kind="bold", halign="center", valign="center")


def base():
    b = rr(OUT_X, OUT_Y, CORNER_R, 0, BASE_H)
    b = b.cut(rr(IN_X, IN_Y, CORNER_R - WALL, FLOOR, BASE_H + 1))
    # horns for the spring bars (inner faces STRAP_W apart)
    for sy in (-1, 1):
        for sx in (-1, 1):
            x0, x1 = sorted((sx * STRAP_W / 2, sx * (STRAP_W / 2 + HORN_T)))
            y0, y1 = sorted((sy * (OUT_Y / 2 - 1.0), sy * (BAR_Y + 2.6)))
            h = box(x0, x1, y0, y1, 0, BASE_H)
            try:
                h = h.edges("|Z").fillet(1.4)
            except Exception:
                pass
            b = b.union(h)
            # blind hole for the spring bar tip, from the inner face of the horn
            xs = sx * STRAP_W / 2
            hole = (cq.Workplane("YZ", origin=(xs, 0, 0)).center(sy * BAR_Y, BAR_Z)
                    .circle(BAR_HOLE_D / 2).extrude(sx * BAR_HOLE_DEPTH))
            b = b.cut(hole)
    # blend the lug outer faces into the rounded case corners (removes the small shoulder)
    try:
        xc = STRAP_W / 2 + HORN_T
        yc = (OUT_Y / 2 - CORNER_R) + math.sqrt(CORNER_R ** 2 - (xc - (OUT_X / 2 - CORNER_R)) ** 2)
        for sx in (-1, 1):
            for sy in (-1, 1):
                sel = cq.selectors.BoxSelector((sx * xc - 0.2, sy * yc - 0.2, -1), (sx * xc + 0.2, sy * yc + 0.2, BASE_H + 1))
                b = b.edges("|Z").edges(sel).fillet(1.5)
    except Exception as e:
        print("lug blend skipped:", e)
    # screw posts with insert holes
    for (x, y) in POST_XY:
        b = b.union(cyl_z(x, y, FLOOR - 0.01, BASE_H, POST_D))
        b = b.cut(cyl_z(x, y, BASE_H - INSERT_DEPTH, BASE_H + 1, INSERT_D))
    # corner stops that hold the LiPo and the charger in place
    def stops(cx, cy, sx_, sy_, hgt, eys=(-1, 1)):
        for ex in (-1, 1):
            for ey in eys:
                x = cx + ex * (sx_ / 2 + 1.5)
                y = cy + ey * (sy_ / 2 + 1.5)
                yield box(x - 1.5, x + 1.5, y - 1.5, y + 1.5, FLOOR - 0.01, FLOOR + hgt)
    cavity = rr(IN_X, IN_Y, CORNER_R - WALL, FLOOR - 0.01, BASE_H)   # clip the stops so none poke through the rounded wall
    for s in stops(0, LIPO_CY, LIPO_X, LIPO_Y, 2.2, eys=(-1,)):   # +Y side: the charger is the stop
        b = b.union(s.intersect(cavity))
    for s in stops(0, TP_CY, TP_X, TP_Y, 2.2):
        b = b.union(s.intersect(cavity))
    # USB-C opening (charger board at the +X wall) and power-switch slot
    b = b.cut(box(IN_X / 2 - 1, OUT_X / 2 + 1, TP_CY - 4.7, TP_CY + 4.7, 2.9, 7.5))
    b = b.cut(box(IN_X / 2 - 1, OUT_X / 2 + 1, -2.0 - 4.9, -2.0 + 4.9, 3.2, 7.2))
    try:
        b = b.faces("<Z").edges().fillet(1.0)
    except Exception:
        pass
    # hidden mark on the inside of the floor, under the battery
    b = b.cut(engrave_up((0, LIPO_CY, FLOOR), SIG, 3.2))
    return b


def lid():
    l = rr(OUT_X, OUT_Y, CORNER_R, BASE_H, TOP_Z)
    # the lid cavity is 1 mm narrower per side than the base cavity, so the lip below is fused to the wall
    l = l.cut(rr(IN_X - 2.0, IN_Y - 2.0, CORNER_R - WALL - 1.0, BASE_H - 1, CEIL_Z))
    try:
        l = l.faces(">Z").edges().fillet(1.5)
    except Exception as e:
        print("lid fillet skipped:", e)
    # alignment lip that drops into the base (notched around the posts)
    lip_o = rr(IN_X - 0.6, IN_Y - 0.6, CORNER_R - WALL - 0.3, BASE_H - 1.2, BASE_H + 0.5)
    lip_i = rr(IN_X - 0.6 - 2.4, IN_Y - 0.6 - 2.4, CORNER_R - WALL - 1.5, BASE_H - 2, BASE_H + 1.5)
    lip = lip_o.cut(lip_i)
    for (x, y) in POST_XY:
        lip = lip.cut(cyl_z(x, y, BASE_H - 2, BASE_H + 1, POST_D + 1.0))
    l = l.union(lip)
    # posts down from the ceiling, screw holes with counterbore
    for (x, y) in POST_XY:
        l = l.union(cyl_z(x, y, BASE_H, CEIL_Z + 0.01, POST_D))
        l = l.cut(cyl_z(x, y, BASE_H - 1, TOP_Z + 1, SCREW_HOLE_D))
        l = l.cut(cyl_z(x, y, TOP_Z - CBORE_DEPTH, TOP_Z + 1, CBORE_D))
    # button holes
    for x in BTN_X:
        l = l.cut(cyl_z(x, BTN_Y, CEIL_Z - 1, TOP_Z + 1, HOLE_D))
    # recess for the logo chip (glued in, then filled level with clear 2-part resin)
    l = l.cut(rr(CHIP_H + 2 * CHIP_CLR, CHIP_W + 2 * CHIP_CLR, 1.7, TOP_Z - POCKET_DEPTH, TOP_Z + 1, 0, CHIP_CY))
    return l


def plunger(kind):
    p = cyl_z(0, 0, 0, FLANGE_T, FLANGE_D).union(cyl_z(0, 0, FLANGE_T - 0.01, FLANGE_T + STEM_H, STEM_D))
    top = FLANGE_T + STEM_H
    if kind == 2:       # dimple
        p = p.cut(cq.Workplane("XY").sphere(3.4).translate((0, 0, top + 2.9)))
    elif kind == 3:     # cross groove
        p = p.cut(box(-STEM_D / 2 - 1, STEM_D / 2 + 1, -0.4, 0.4, top - 0.5, top + 1))
        p = p.cut(box(-0.4, 0.4, -STEM_D / 2 - 1, STEM_D / 2 + 1, top - 0.5, top + 1))
    try:
        p = p.faces(">Z").edges().chamfer(0.3)
    except Exception:
        pass
    return p


def logo_chip():
    """Plate (colour A) with the raised logo (colour B) on top. Logo top = lid top when fitted."""
    chip = rr(CHIP_W, CHIP_H, 1.5, 0, CHIP_BASE)
    z0, z1 = CHIP_BASE - 0.01, CHIP_BASE + CHIP_LOGO
    layer = None
    for depth in sorted(set(d for d, _ in LOGO_CONTOURS)):
        shapes = None
        for d, pts in LOGO_CONTOURS:
            if d != depth:
                continue
            sh = cq.Workplane("XY", origin=(0, 0, z0)).polyline(pts).close().extrude(z1 - z0)
            shapes = sh if shapes is None else shapes.union(sh)
        if layer is None:
            layer = shapes
        elif depth % 2 == 1:
            layer = layer.cut(shapes)      # holes (inside the glasses frame, the O, the D ...)
        else:
            layer = layer.union(shapes)    # islands inside holes (the three lines in the lens)
    return chip.union(layer).rotate((0, 0, 0), (0, 0, 1), 90)   # sideways: reads along the strap (+Y), letter tops point to -X


def build():
    return {
        "KD06-A_case_base": base(),
        "KD06-B_case_lid": lid(),
        "KD06-C1_button_plain": plunger(1),
        "KD06-C2_button_dimple": plunger(2),
        "KD06-C3_button_groove": plunger(3),
        "KD06-D_logo_chip": logo_chip(),
    }


def print_pose(name, p):
    s = p.rotate((0, 0, 0), (1, 0, 0), 180) if name == "KD06-B_case_lid" else p
    bb = s.val().BoundingBox()
    return s.translate((-bb.center.x, -bb.center.y, -bb.zmin))


